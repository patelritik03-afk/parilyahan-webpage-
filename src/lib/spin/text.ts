// Where a player came from (QR on tables, kiosk, social, ads...). Free text is cleaned to this shape.
export function cleanSource(value: unknown) {
  if (typeof value !== "string") return "website";
  const v = value.toLowerCase().replace(/[^a-z0-9-]/g, "").slice(0, 40);
  return v || "website";
}

// "psk 7k3q 9mzt", "PSK-7K3Q-9MZT" or "7K3Q9MZT" -> "PSK-7K3Q-9MZT"; null if it can't be a code.
export function formatCouponCode(value: string) {
  const raw = value.toUpperCase().replace(/[^A-Z0-9]/g, "").replace(/^PSK/, "");
  return raw.length === 8 ? `PSK-${raw.slice(0, 4)}-${raw.slice(4)}` : null;
}
